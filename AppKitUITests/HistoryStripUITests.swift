import AppKit
import XCTest

final class HistoryStripUITests: XCTestCase {
    @MainActor private lazy var app = XCUIApplication()

    override func setUpWithError() throws {
        continueAfterFailure = false
    }

    /// Each test launches with its own history and its own pasteboard, away from the real ones.
    @MainActor private func launchApp() {
        let app = self.app
        addTeardownBlock { @MainActor in
            app.terminate()
        }
        useFreshHistory()
        app.launch()
    }

    @MainActor private func useFreshHistory() {
        app.launchEnvironment["APPKIT_UI_TEST_ID"] = UUID().uuidString
    }

    /// The private pasteboard the app watches during this test.
    @MainActor private var pasteboard: NSPasteboard {
        let identifier = app.launchEnvironment["APPKIT_UI_TEST_ID"] ?? ""
        return NSPasteboard(name: NSPasteboard.Name("appkit.uitest.\(identifier)"))
    }

    @MainActor private func copy(_ text: String) {
        pasteboard.clearContents()
        pasteboard.setString(text, forType: .string)
    }

    @MainActor private var statusItem: XCUIElement {
        app.statusItems["statusItem.button"]
    }

    @MainActor private var strip: XCUIElement {
        app.descendants(matching: .any)["history.strip"]
    }

    @MainActor private var cards: XCUIElementQuery {
        app.descendants(matching: .any).matching(identifier: "history.card")
    }

    @MainActor private func openStrip() {
        XCTAssertTrue(statusItem.waitForExistence(timeout: 5))
        statusItem.click()
        // A real click elsewhere on this Mac closes the strip, as it should: try once more.
        if !strip.waitForExistence(timeout: 5) {
            statusItem.click()
        }
        XCTAssertTrue(strip.waitForExistence(timeout: 5))
    }

    @MainActor private func waitForCards(_ count: Int) {
        let done = expectation(for: NSPredicate(format: "count == %d", count), evaluatedWith: cards)
        if XCTWaiter.wait(for: [done], timeout: 5) != .completed {
            let labels = cards.allElementsBoundByIndex.map(\.label)
            XCTFail("Attendu \(count) cartes, trouvé \(labels.count) : \(labels)")
        }
    }

    /// Leaves time for the half-second polling to see the copy.
    @MainActor private func copyAndWait(_ text: String) {
        copy(text)
        Thread.sleep(forTimeInterval: 1)
    }

    @MainActor func testIconOpensAndEscapeCloses() {
        launchApp()
        openStrip()
        strip.typeKey(.escape, modifierFlags: [])
        XCTAssertTrue(strip.waitForNonExistence(timeout: 5))
    }

    @MainActor func testClickElsewhereCloses() {
        launchApp()
        openStrip()
        // A point above the strip, over another app.
        strip.coordinate(withNormalizedOffset: CGVector(dx: 0.5, dy: -1.5)).click()
        XCTAssertTrue(strip.waitForNonExistence(timeout: 5))
    }

    @MainActor func testCopiesShowNewestFirstWithSourceAndTime() {
        launchApp()
        copyAndWait("première copie UI")
        copyAndWait("seconde copie UI")
        openStrip()
        waitForCards(2)
        let label = cards.element(boundBy: 0).label
        XCTAssertTrue(label.contains("seconde copie UI"), label)
        XCTAssertTrue(label.contains("instant") || label.contains("now"), label)
        XCTAssertTrue(cards.element(boundBy: 1).label.contains("première copie UI"))
    }

    @MainActor func testACopyWhileOpenAppearsWithoutMovingTheSelection() {
        launchApp()
        copyAndWait("a")
        copyAndWait("b")
        openStrip()
        waitForCards(2)
        strip.typeKey(.rightArrow, modifierFlags: [])
        XCTAssertTrue(cards.element(boundBy: 1).isSelected)

        copy("c")
        waitForCards(3)
        XCTAssertTrue(cards.element(boundBy: 2).isSelected)
        XCTAssertFalse(cards.element(boundBy: 0).isSelected)
    }

    @MainActor private func copyMarked(_ text: String, marker: String) {
        let type = NSPasteboard.PasteboardType(marker)
        pasteboard.declareTypes([.string, type], owner: nil)
        pasteboard.setString(text, forType: .string)
        pasteboard.setString("", forType: type)
        Thread.sleep(forTimeInterval: 1)
    }

    @MainActor private func toggleAutoGeneratedOption() {
        statusItem.rightClick()
        let item = app.menuItems["statusItem.settings"]
        XCTAssertTrue(item.waitForExistence(timeout: 5))
        item.click()
        let toggle = app.descendants(matching: .any)["settings.keepsAutoGeneratedCopies"]
        XCTAssertTrue(toggle.waitForExistence(timeout: 5))
        attachScreenshot(named: "Réglages", of: app.windows.firstMatch)
        toggle.click()
        app.windows.firstMatch.typeKey("w", modifierFlags: .command)
    }

    @MainActor func testMarkedCopiesAreLeftOut() {
        launchApp()
        copyMarked("confidentiel", marker: "org.nspasteboard.ConcealedType")
        copyMarked("temporaire", marker: "org.nspasteboard.TransientType")
        copyMarked("1password", marker: "com.agilebits.onepassword")
        copyMarked("généré", marker: "org.nspasteboard.AutoGeneratedType")
        copyAndWait("public")
        openStrip()
        waitForCards(1)
        XCTAssertTrue(cards.element(boundBy: 0).label.contains("public"))
    }

    @MainActor func testTheOptionKeepsAutoGeneratedCopies() {
        launchApp()
        toggleAutoGeneratedOption()
        // The option is stored in the app's real settings: always switch it back.
        addTeardownBlock { @MainActor [self] in
            if !app.exists { app.launch() }
            toggleAutoGeneratedOption()
        }
        copyMarked("généré", marker: "org.nspasteboard.AutoGeneratedType")
        openStrip()
        waitForCards(1)
        strip.typeKey(.escape, modifierFlags: [])
        XCTAssertTrue(strip.waitForNonExistence(timeout: 5))
    }

    @MainActor func testCopiesSurviveARelaunchInTheSameOrder() {
        launchApp()
        copyAndWait("ancien")
        copyAndWait("récent")
        // Same history as the launch before.
        app.terminate()
        app.launch()

        openStrip()
        waitForCards(2)
        XCTAssertTrue(cards.element(boundBy: 0).label.contains("récent"))
        XCTAssertTrue(cards.element(boundBy: 1).label.contains("ancien"))
    }

    @MainActor func testAMissingKeyErasesNothingUntilConfirmed() {
        launchApp()
        copyAndWait("gardé")
        app.terminate()
        app.launchEnvironment["APPKIT_UI_TEST_DELETE_KEY"] = "1"
        app.launch()

        let retry = app.buttons["Réessayer"]
        let startOver = app.buttons["Repartir à zéro…"]
        XCTAssertTrue(retry.waitForExistence(timeout: 10))
        XCTAssertTrue(app.staticTexts["Votre historique est chiffré avec une clé introuvable sur ce Mac"].exists)

        retry.click()
        XCTAssertTrue(retry.waitForExistence(timeout: 5))

        startOver.click()
        XCTAssertTrue(app.staticTexts["Supprimer tout l’historique, épinglés compris ?"].waitForExistence(timeout: 5))
        app.buttons["Annuler"].click()
        XCTAssertTrue(retry.waitForExistence(timeout: 5))

        startOver.click()
        let deleteAll = app.buttons["Tout supprimer"]
        XCTAssertTrue(deleteAll.waitForExistence(timeout: 5))
        deleteAll.click()

        openStrip()
        XCTAssertTrue(app.descendants(matching: .any)["history.empty"].waitForExistence(timeout: 5))
    }

    @MainActor func testTheGlobalShortcutOpensAndClosesTheStrip() {
        launchApp()
        XCTAssertTrue(statusItem.waitForExistence(timeout: 5))
        // Past the launch, for the shortcut to be registered.
        Thread.sleep(forTimeInterval: 1)

        XCUIApplication(bundleIdentifier: "com.apple.finder").activate()
        pressGlobalShortcut()
        XCTAssertTrue(strip.waitForExistence(timeout: 5))

        pressGlobalShortcut()
        XCTAssertTrue(strip.waitForNonExistence(timeout: 5))
    }

    @MainActor func testEnterAfterTheShortcutPutsTheNewestCopyBack() {
        launchApp()
        copyAndWait("ancien")
        copyAndWait("récent")
        pressGlobalShortcut()
        XCTAssertTrue(strip.waitForExistence(timeout: 5))
        waitForCards(2)
        XCTAssertTrue(cards.element(boundBy: 0).isSelected)

        copy("autre chose")
        Thread.sleep(forTimeInterval: 1)
        strip.typeKey(.return, modifierFlags: [])
        XCTAssertTrue(strip.waitForNonExistence(timeout: 5))
        XCTAssertEqual(pasteboardText(), "récent")
    }

