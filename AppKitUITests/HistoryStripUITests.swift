        XCTAssertEqual(pasteboardText(), "texte")
    }

    @MainActor private func makePNG() throws -> Data {
        let bitmap = try XCTUnwrap(NSBitmapImageRep(
            bitmapDataPlanes: nil, pixelsWide: 1000, pixelsHigh: 667,
            bitsPerSample: 8, samplesPerPixel: 4, hasAlpha: true, isPlanar: false,
            colorSpaceName: .deviceRGB, bytesPerRow: 0, bitsPerPixel: 0
        ))
        NSGraphicsContext.saveGraphicsState()
        NSGraphicsContext.current = NSGraphicsContext(bitmapImageRep: bitmap)
        NSColor.systemTeal.setFill()
        NSRect(x: 0, y: 0, width: 1000, height: 667).fill()
        NSGraphicsContext.restoreGraphicsState()
        return try XCTUnwrap(bitmap.representation(using: .png, properties: [:]))
    }

    @MainActor private func makePDF() throws -> Data {
        let data = NSMutableData()
        let consumer = try XCTUnwrap(CGDataConsumer(data: data))
        var box = CGRect(x: 0, y: 0, width: 200, height: 300)
        let context = try XCTUnwrap(CGContext(consumer: consumer, mediaBox: &box, nil))
        for _ in 0..<2 {
            context.beginPDFPage(nil)
            context.endPDFPage()
        }
        context.closePDF()
        return data as Data
    }

    @MainActor private func copyData(_ data: Data, type: String) {
        pasteboard.clearContents()
        pasteboard.setData(data, forType: NSPasteboard.PasteboardType(type))
        Thread.sleep(forTimeInterval: 1)
    }

    @MainActor func testImagesAndPDFsShowTheirDetailsAndComeBackIdentical() throws {
        launchApp()
        let png = try makePNG()
        let pdf = try makePDF()
        copyData(pdf, type: "com.adobe.pdf")
        copyData(png, type: "public.png")
        openStrip()
        waitForCards(2)

        XCTAssertTrue(cards.element(boundBy: 0).label.contains("× 667 px"), cards.element(boundBy: 0).label)
        XCTAssertTrue(cards.element(boundBy: 1).label.contains("PDF"), cards.element(boundBy: 1).label)
        XCTAssertTrue(cards.element(boundBy: 1).label.contains("2 pages"), cards.element(boundBy: 1).label)
        attachScreenshot(named: "Image et PDF")

        cards.element(boundBy: 1).click()
        XCTAssertTrue(strip.waitForNonExistence(timeout: 5))
        XCTAssertEqual(pasteboard.data(forType: NSPasteboard.PasteboardType("com.adobe.pdf")), pdf)

        openStrip()
        waitForCards(2)
        cards.element(boundBy: 1).click()
        XCTAssertTrue(strip.waitForNonExistence(timeout: 5))
        XCTAssertEqual(pasteboard.data(forType: NSPasteboard.PasteboardType("public.png")), png)
    }

    @MainActor private func copyRichText(_ text: String) throws -> Data {
        let attributed = NSAttributedString(
            string: text,
            attributes: [.font: NSFont.boldSystemFont(ofSize: 18), .foregroundColor: NSColor.systemRed]
        )
        let rtf = try XCTUnwrap(attributed.rtf(from: NSRange(location: 0, length: attributed.length)))
        pasteboard.clearContents()
        pasteboard.setString(text, forType: .string)
        pasteboard.setData(rtf, forType: .rtf)
        Thread.sleep(forTimeInterval: 1)
        return rtf
    }

    @MainActor func testARichTextKeepsItsFormatsUnlessAskedForPlainText() throws {
        launchApp()
        let rtf = try copyRichText("Texte en gras")
        openStrip()
        waitForCards(1)
        XCTAssertTrue(cards.element(boundBy: 0).label.contains("Texte enrichi"), cards.element(boundBy: 0).label)

        strip.typeKey(.return, modifierFlags: [])
        XCTAssertTrue(strip.waitForNonExistence(timeout: 5))
        XCTAssertEqual(pasteboard.data(forType: .rtf), rtf)

        openStrip()
        waitForCards(1)
        strip.typeKey(.return, modifierFlags: .shift)
        XCTAssertTrue(strip.waitForNonExistence(timeout: 5))
        XCTAssertNil(pasteboard.data(forType: .rtf))
        XCTAssertEqual(pasteboardText(), "Texte en gras")
    }

