import AppKitCore
import Foundation

extension ClipCapturePolicy {
    nonisolated static let addedAppsKey = "excludedAppsAdded"
    nonisolated static let removedDefaultAppsKey = "excludedAppsRemovedDefaults"
    nonisolated static let excludedCategoriesKey = "excludedCategories"

    /// The rules the user chose. Read at each copy, as the settings can change them at any moment.
    nonisolated static func current(in defaults: UserDefaults) -> ClipCapturePolicy {
        let added = (defaults.dictionary(forKey: addedAppsKey) as? [String: String]) ?? [:]
        let removed = Set(defaults.stringArray(forKey: removedDefaultAppsKey) ?? [])
        return ClipCapturePolicy(
            keepsAutoGenerated: defaults.bool(forKey: UserDefaults.keepsAutoGeneratedCopiesKey),
            excludedApps: ClipExcludedApp.defaultIdentifiers.subtracting(removed).union(added.keys),
            excludedCategories: Set((defaults.stringArray(forKey: excludedCategoriesKey) ?? []).compactMap(ClipCategory.init))
        )
    }
}
