import AppKitCore
import SwiftUI

/// What is never kept: marked copies, chosen categories and chosen apps.
struct PrivacySettingsSection: View {
    let defaults: UserDefaults

    @AppStorage(UserDefaults.keepsAutoGeneratedCopiesKey) private var keepsAutoGeneratedCopies = false
    @State private var excludedCategories: Set<ClipCategory> = []
    @State private var addedApps: [String: String] = [:]
    @State private var removedDefaults: Set<String> = []
    @State private var isPickingApp = false

    private var excludedApps: [ClipExcludedApp] {
        let kept = ClipExcludedApp.defaults.filter { !removedDefaults.contains($0.bundleIdentifier) }
        let added = addedApps
            .map { ClipExcludedApp(bundleIdentifier: $0.key, name: $0.value) }
            .sorted { $0.name.localizedStandardCompare($1.name) == .orderedAscending }
        return kept + added
    }

    var body: some View {
        Section("Confidentialité") {
            LabeledContent {
                EmptyView()
            } label: {
                Text("Mots de passe et copies confidentielles")
                Text("Jamais gardés, et jamais écrits sur le disque, même temporairement.")
            }

            Toggle(isOn: $keepsAutoGeneratedCopies) {
                Text("Garder les copies générées automatiquement")
                Text("Celles qu’une app crée seule, sans que vous ayez copié quoi que ce soit.")
            }
            .accessibilityIdentifier("settings.keepsAutoGeneratedCopies")

            LabeledContent {
                Menu(categorySummary) {
                    ForEach(ClipCategory.allCases, id: \.self) { category in
                        Toggle(title(of: category), isOn: binding(for: category))
                    }
                }
                .fixedSize()
                .accessibilityIdentifier("settings.excludedCategories")
            } label: {
                Text("Catégories exclues")
                Text("Une copie de ces catégories n’est plus gardée. Celles déjà gardées restent.")
            }
        }

        Section("Apps exclues") {
            ForEach(excludedApps) { app in
                LabeledContent {
                    Button("Retirer") { remove(app) }
                        .accessibilityLabel(String(localized: "Retirer \(displayName(of: app))"))
                        .accessibilityIdentifier("settings.removeApp.\(app.bundleIdentifier)")
                } label: {
                    Text(verbatim: displayName(of: app))
                    if ClipExcludedApp.defaultIdentifiers.contains(app.bundleIdentifier) {
                        Text("par défaut")
                    }
                }
            }
            Button("Ajouter une app…") { isPickingApp = true }
                .accessibilityIdentifier("settings.addApp")
        }
        .onAppear(perform: load)
        .sheet(isPresented: $isPickingApp) {
            ExcludedAppPickerView(alreadyExcluded: Set(excludedApps.map(\.bundleIdentifier)), onExclude: add)
        }
    }

    private var categorySummary: String {
        let titles = ClipCategory.allCases.filter(excludedCategories.contains).map(title)
        return titles.isEmpty ? String(localized: "Aucune") : titles.formatted(.list(type: .and))
    }

    private func binding(for category: ClipCategory) -> Binding<Bool> {
        Binding(
            get: { excludedCategories.contains(category) },
            set: { isExcluded in
                if isExcluded {
                    excludedCategories.insert(category)
                } else {
                    excludedCategories.remove(category)
                }
                defaults.set(excludedCategories.map(\.rawValue), forKey: ClipCapturePolicy.excludedCategoriesKey)
            }
        )
    }

    private func load() {
        excludedCategories = Set((defaults.stringArray(forKey: ClipCapturePolicy.excludedCategoriesKey) ?? []).compactMap(ClipCategory.init))
        addedApps = (defaults.dictionary(forKey: ClipCapturePolicy.addedAppsKey) as? [String: String]) ?? [:]
        removedDefaults = Set(defaults.stringArray(forKey: ClipCapturePolicy.removedDefaultAppsKey) ?? [])
    }

    private func add(_ app: ClipExcludedApp) {
        if ClipExcludedApp.defaultIdentifiers.contains(app.bundleIdentifier) {
            removedDefaults.remove(app.bundleIdentifier)
        } else {
            addedApps[app.bundleIdentifier] = app.name
        }
        save()
    }

    private func remove(_ app: ClipExcludedApp) {
        if ClipExcludedApp.defaultIdentifiers.contains(app.bundleIdentifier) {
            removedDefaults.insert(app.bundleIdentifier)
        } else {
            addedApps[app.bundleIdentifier] = nil
        }
        save()
    }

    private func save() {
        defaults.set(addedApps, forKey: ClipCapturePolicy.addedAppsKey)
        defaults.set(Array(removedDefaults), forKey: ClipCapturePolicy.removedDefaultAppsKey)
    }

    /// The two apps of Apple carry their name in the language of the Mac.
    private func displayName(of app: ClipExcludedApp) -> String {
        switch app.bundleIdentifier {
        case "com.apple.Passwords": String(localized: "Mots de passe")
        case "com.apple.keychainaccess": String(localized: "Trousseaux d’accès")
        default: app.name
        }
    }

    private func title(of category: ClipCategory) -> String {
        switch category {
        case .text: String(localized: "Texte")
        case .richText: String(localized: "Texte enrichi")
        case .link: String(localized: "Lien")
        case .image: String(localized: "Image")
        case .files: String(localized: "Fichiers")
        case .color: String(localized: "Couleur")
        case .pdf: String(localized: "PDF")
        case .other: String(localized: "Autre")
        }
    }
}
