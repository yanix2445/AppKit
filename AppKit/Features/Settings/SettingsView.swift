import AppKit
import AppKitSystem
import SwiftUI

/// The settings. Only the general and privacy options exist so far.
struct SettingsView: View {
    let launchAtLogin: LaunchAtLoginController

    @AppStorage(UserDefaults.keepsAutoGeneratedCopiesKey) private var keepsAutoGeneratedCopies = false

    var body: some View {
        Form {
            Section("Général") {
                Toggle(isOn: launchAtLoginBinding) {
                    Text("Lancer AppKit à l’ouverture de session")
                    Text("Pour que vos copies soient gardées dès le démarrage du Mac.")
                }
                .accessibilityIdentifier("settings.launchAtLogin")

                if launchAtLogin.status == .requiresApproval {
                    LabeledContent {
                        Button("Ouvrir les Réglages Système", action: launchAtLogin.openSystemSettings)
                    } label: {
                        Text("En attente de votre accord dans les Réglages Système.")
                    }
                }
                if launchAtLogin.hasFailed {
                    Text("macOS a refusé ce changement. Réessayez depuis les Réglages Système.")
                        .font(.callout)
                        .foregroundStyle(.secondary)
                }
            }

            Section("Confidentialité") {
                LabeledContent {
                    EmptyView()
                } label: {
                    Text("Mots de passe et copies confidentielles")
                    Text("Jamais gardés, et jamais écrits sur le disque, même temporairement.")
                }

                Toggle(isOn: $keepsAutoGeneratedCopies) {
                    Text("Garder les copies générées automatiquement")
                    Text("Celles qu’une app crée seule, sans que vous ayez copié quoi que ce soit.")
                }
                .accessibilityIdentifier("settings.keepsAutoGeneratedCopies")
            }
        }
        .formStyle(.grouped)
        .frame(width: SettingsMetrics.width)
        .fixedSize(horizontal: false, vertical: true)
        .onAppear(perform: launchAtLogin.refresh)
        .onReceive(NotificationCenter.default.publisher(for: NSApplication.didBecomeActiveNotification)) { _ in
            launchAtLogin.refresh()
        }
    }

    private var launchAtLoginBinding: Binding<Bool> {
        Binding(
            get: { launchAtLogin.status != .disabled },
            set: { launchAtLogin.setEnabled($0) }
        )
    }
}
