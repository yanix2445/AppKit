import AppKitCore
import AppKitSystem
import AppKitSystemTesting
import Foundation
import Testing

struct ClipboardMonitorTests {
    private let source = ClipSource(name: "Notes", bundleIdentifier: "com.apple.Notes")

    private func makeMonitor(
        _ pasteboard: FakePasteboardService,
        policy: ClipboardPollingPolicy = .standard
    ) -> ClipboardMonitor {
        ClipboardMonitor(
            pasteboard: pasteboard,
            frontmostApp: FakeFrontmostAppService(source: source),
            policy: policy
        )
    }

    @Test func ignoresWhatWasCopiedBeforeLaunch() async {
        let pasteboard = FakePasteboardService()
        pasteboard.copy(text: "avant")
        let monitor = makeMonitor(pasteboard)
        #expect(await monitor.poll() == nil)
    }

    @Test func capturesANewTextWithItsSource() async throws {
        let pasteboard = FakePasteboardService()
        let monitor = makeMonitor(pasteboard)
        pasteboard.copy(text: "bonjour")
        let capture = try #require(await monitor.poll())
        #expect(capture.clip.content == .text("bonjour"))
        #expect(capture.clip.source == source)
    }

    @Test func capturesACopyOnlyOnce() async {
        let pasteboard = FakePasteboardService()
        let monitor = makeMonitor(pasteboard)
        pasteboard.copy(text: "bonjour")
        _ = await monitor.poll()
        #expect(await monitor.poll() == nil)
    }

    @Test(arguments: [nil, ""] as [String?])
    func ignoresACopyWithoutText(text: String?) async {
        let pasteboard = FakePasteboardService()
        let monitor = makeMonitor(pasteboard)
        pasteboard.copy(text: text)
        #expect(await monitor.poll() == nil)
    }

    @Test func restoringPutsTheExactTextBackWithoutANewCapture() async {
        let pasteboard = FakePasteboardService()
        let monitor = makeMonitor(pasteboard)
        let text = "  deux lignes\n et des espaces  "

        await monitor.restore(Clip(content: .text(text), source: source, capturedAt: .now))

        #expect(pasteboard.readText() == text)
        #expect(await monitor.poll() == nil)
    }

    @Test func restoringAsPlainTextWritesTheTextAloneAndLeavesTheCopyAsItIs() async {
        let pasteboard = FakePasteboardService()
        let monitor = makeMonitor(pasteboard)
        let clip = Clip(content: .text("sans mise en forme"), source: source, capturedAt: .now)

        await monitor.restore(clip, style: .plainText)

        #expect(pasteboard.readText() == "sans mise en forme")
        #expect(pasteboard.readTypes().isEmpty)
        #expect(clip.content == .text("sans mise en forme"))
        #expect(await monitor.poll() == nil)
    }

    @Test func aCopyAfterARestoreIsStillCaptured() async {
        let pasteboard = FakePasteboardService()
        let monitor = makeMonitor(pasteboard)
        await monitor.restore(Clip(content: .text("remis"), source: source, capturedAt: .now))
        pasteboard.copy(text: "nouveau")
        #expect(await monitor.poll()?.clip.content == .text("nouveau"))
    }

    @Test(arguments: ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "com.agilebits.onepassword", "org.nspasteboard.AutoGeneratedType"])
    func aRefusedCopyIsNeverEvenRead(marker: String) async {
        let pasteboard = FakePasteboardService()
        let monitor = makeMonitor(pasteboard)
        pasteboard.copy(text: "motdepasse", types: [marker])

        #expect(await monitor.poll() == nil)
        #expect(pasteboard.readCount == 0)
    }

    @Test func aRefusedCopyDoesNotBlockTheNextOne() async {
        let pasteboard = FakePasteboardService()
        let monitor = makeMonitor(pasteboard)
        pasteboard.copy(text: "motdepasse", types: ["org.nspasteboard.ConcealedType"])
        _ = await monitor.poll()
        pasteboard.copy(text: "public")
        #expect(await monitor.poll()?.clip.content == .text("public"))
    }

    @Test func aPrivateCopyLandingDuringTheReadIsNotKept() async {
        let pasteboard = FakePasteboardService()
        let monitor = makeMonitor(pasteboard)
        pasteboard.copy(text: "public")
        pasteboard.replaceDuringNextRead(text: "motdepasse", types: ["org.nspasteboard.ConcealedType"])

        #expect(await monitor.poll() == nil)
        #expect(await monitor.poll() == nil)
    }

    @Test func theCapturePolicyIsReadAtEachCopy() async {
        let pasteboard = FakePasteboardService()
        let monitor = ClipboardMonitor(
            pasteboard: pasteboard,
            frontmostApp: FakeFrontmostAppService(source: source),
            capturePolicy: { ClipCapturePolicy(keepsAutoGenerated: true) }
        )
        pasteboard.copy(text: "généré", types: ["org.nspasteboard.AutoGeneratedType"])
        #expect(await monitor.poll()?.clip.content == .text("généré"))
    }

    @Test func aCopyDuringAPauseIsNeverReadNorCapturedLater() async {
        let pasteboard = FakePasteboardService()
        let monitor = makeMonitor(pasteboard)
        await monitor.setPaused(true)
        pasteboard.copy(text: "pendant la pause")
        #expect(await monitor.poll() == nil)
        #expect(pasteboard.readCount == 0)

        await monitor.setPaused(false)
        #expect(await monitor.poll() == nil)
        pasteboard.copy(text: "après la pause")
        #expect(await monitor.poll()?.clip.content == .text("après la pause"))
    }

    @Test(arguments: ["public.png", "public.tiff", "public.jpeg", "public.heic", "com.compuserve.gif"])
    func anImageIsCapturedWithAllItsFormats(type: String) async throws {
        let pasteboard = FakePasteboardService()
        let monitor = makeMonitor(pasteboard)
        let formats = [
            ClipRepresentation(type: type, data: Data([0xFF, 0x00, 0x7F])),
            ClipRepresentation(type: "com.exemple.prive", data: Data([9, 8])),
        ]
        pasteboard.copy(formats: formats)

        let capture = try #require(await monitor.poll())

        #expect(capture.formats == formats)
        #expect(capture.clip.content == .image(ClipMedia(byteCount: 5, isProcessing: true)))
    }

    @Test func aPDFIsCaptured() async throws {
        let pasteboard = FakePasteboardService()
        let monitor = makeMonitor(pasteboard)
        let formats = [ClipRepresentation(type: "com.adobe.pdf", data: Data("%PDF".utf8))]
        pasteboard.copy(formats: formats)

        let capture = try #require(await monitor.poll())

        #expect(capture.formats == formats)
        #expect(capture.clip.content == .pdf(ClipMedia(byteCount: 4, isProcessing: true)))
    }

    @Test func restoringAnImagePutsBackEveryFormatWithoutANewCapture() async {
        let pasteboard = FakePasteboardService()
        let monitor = makeMonitor(pasteboard)
        let formats = [ClipRepresentation(type: "public.png", data: Data([1, 2, 3]))]
        let clip = Clip(content: .image(ClipMedia(byteCount: 3)), source: source, capturedAt: .now)

        await monitor.restore(clip, formats: formats)

        #expect(pasteboard.readFormats() == formats)
        #expect(await monitor.poll() == nil)
    }

    @Test func thePollingStreamDeliversACopy() async throws {
        let pasteboard = FakePasteboardService()
        let monitor = makeMonitor(
            pasteboard,
            policy: ClipboardPollingPolicy(interval: .milliseconds(5), tolerance: .milliseconds(1))
        )
        var iterator = await monitor.captures().makeAsyncIterator()
        pasteboard.copy(text: "bonjour")
        let capture = try #require(await iterator.next())
        #expect(capture.clip.content == .text("bonjour"))
    }
}
