/// Decides whether a copy may be kept, from its types, its source app and its category.
public struct ClipCapturePolicy: Equatable, Sendable {
    /// Always refused: passwords, codes and other copies that apps mark as private or short-lived.
    public static let refusedTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "com.agilebits.onepassword",
    ]

    /// Refused unless the user chooses to keep them.
    public static let autoGeneratedType = "org.nspasteboard.AutoGeneratedType"

    /// Holds the identifier of the app that made the copy, when that app says so.
    public static let sourceMarkerType = "org.nspasteboard.source"

    public let keepsAutoGenerated: Bool
    public let excludedApps: Set<String>
    public let excludedCategories: Set<ClipCategory>

    public init(
        keepsAutoGenerated: Bool = false,
        excludedApps: Set<String> = ClipExcludedApp.defaultIdentifiers,
        excludedCategories: Set<ClipCategory> = []
    ) {
        self.keepsAutoGenerated = keepsAutoGenerated
        self.excludedApps = excludedApps
        self.excludedCategories = excludedCategories
    }

    public func allows(types: Set<String>) -> Bool {
        guard types.isDisjoint(with: Self.refusedTypes) else { return false }
        return keepsAutoGenerated || !types.contains(Self.autoGeneratedType)
    }

    public func allows(appIdentifier: String?) -> Bool {
        guard let appIdentifier else { return true }
        return !excludedApps.contains(appIdentifier)
    }

    public func allows(category: ClipCategory) -> Bool {
        !excludedCategories.contains(category)
    }
}
